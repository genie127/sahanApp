// ─── 태블릿(iPad 등) 반응형 ────────────────────────────────────────────────
// 태블릿으로 간주하는 최소 너비(dp). iPad mini(768) 포함.
export const TabletBreakpoint = 768;

/** 현재 창 너비가 태블릿 크기인지 판별 */
export function isTabletWidth(width: number): boolean {
  return width >= TabletBreakpoint;
}

